"""Render the tables of docs/CALIBRATION_SWEEP.md from results/calibration/*.jsonl, so the write-up cannot drift from the data.

    python scripts/render_calibration.py > /tmp/tables.md
"""

from __future__ import annotations

import json
from pathlib import Path

from courtroom.cases import PLAIN_CASES
from courtroom.gametheory.calibration import choose, evaluate, exposed, real_play_cases

SHORT = {
    "helix-espionage": "helix", "aurora-defi": "aurora", "kestrel-av": "kestrel", "edge-empty-docket": "empty",
    "edge-mutual-exclusion": "mutual", "edge-poisoned-tree": "poison", "edge-defense-only": "defonly",
}
ABBR = {"mixed": "M", "pure": "P", "dominance-solvable": "D", "none": "N"}


def load(path: str) -> list[dict]:
    p = Path(path)
    return [json.loads(line) for line in p.read_text().splitlines()] if p.exists() else []


def cell(m: dict) -> str:
    # One decimal, never rounded to a whole percent: half-way values such as 99.5 must not print as 100.
    return f"{ABBR[m['label']]} {100 * m['label_stability']:.1f}/{100 * m['support_stability']:.1f}"


def events_table(recs: list[dict]) -> str:
    base = next(r for r in recs if r["name"] == "events-off")
    exp = [cid for cid, c in PLAIN_CASES.items() if exposed(c)]
    ids = list(PLAIN_CASES)
    head = "| Setting | " + " | ".join(SHORT[c] for c in ids) + " | (a) | (b) | (c) | min stab. |\n|---|" + "---|" * (len(ids) + 4)
    rows = [head]
    for r in recs:
        cells = " | ".join(cell(r["cases"][c]) for c in ids)
        if r["events_on"]:
            e = evaluate(r, base, exp)
            flags = f"{'yes' if e['a'] else 'no'} ({e['risen_cells']}/{e['flat_cells']}) | {'yes' if e['b'] else 'no'} ({len(e['contested'])}) | {'yes' if e['c'] else 'no'} | {e['min_stability']:.3f}"
        else:
            flags = "- | - | - | -"
        rows.append(f"| {r['name']} | {cells} | {flags} |")
    return "\n".join(rows)


def strict_table(recs: list[dict]) -> str:
    base = next(r for r in recs if r["name"] == "events-off")
    real = real_play_cases(base)
    exp = [c for c, k in PLAIN_CASES.items() if exposed(k)]
    rows = ["| Setting | (a) flat cells risen | (b) contested of " + str(len(real)) + " | (c) all stable | min stab. |", "|---|---|---|---|---|"]
    for r in recs:
        if not r["events_on"]:
            continue
        e = evaluate(r, base, exp, scope=real)
        rows.append(f"| {r['name']} | {'yes' if e['a'] else 'no'} ({e['risen_cells']}/{e['flat_cells']}) | {'yes' if e['b'] else 'no'} ({len(e['contested'])}) | {'yes' if e['c'] else 'no'} | {e['min_stability']:.3f} |")
    return "\n".join(rows)


def variance_table(recs: list[dict], names: list[str]) -> str:
    ids = [c for c in PLAIN_CASES if exposed(PLAIN_CASES[c])]
    out = ["| Case, seat, strategy | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    by = {r["name"]: r for r in recs}
    for cid in ids:
        for side in ("prosecution", "defense"):
            for s in ("aggressive", "conservative", "adaptive", "mixed:0.5"):
                out.append(f"| {SHORT[cid]} {side[:4]} {s} | " + " | ".join(f"{by[n]['cases'][cid]['sd'][side][s]:.2f}" for n in names) + " |")
    return "\n".join(out)


def cases_table(recs: list[dict], case_id: str) -> str:
    rows = ["| Value | Label | Label stab. | Support stab. | Win rate (min to max) |", "|---|---|---|---|---|"]
    for r in recs:
        if r["case"] == case_id:
            rows.append(f"| {r['value']} | {r['label']} | {100 * r['label_stability']:.1f}% | {100 * r['support_stability']:.1f}% | {100 * r['win_min']:.1f}% to {100 * r['win_max']:.1f}% |")
    return "\n".join(rows)


if __name__ == "__main__":
    events = load("results/calibration/events.jsonl")
    cases = load("results/calibration/cases.jsonl")
    base = next(r for r in events if r["name"] == "events-off")
    print("<!-- generated by scripts/render_calibration.py -->\n")
    print("### Events sweep\n")
    print(events_table(events))
    print("\n### Selection\n")
    print("```json\n" + json.dumps(choose(events, base, [c for c, k in PLAIN_CASES.items() if exposed(k)]), indent=1) + "\n```")
    print("\n### Strict reading (real-play cases only)\n")
    print(strict_table(events))
    print("\n### Variance (payoff sd)\n")
    print(variance_table(events, ["events-off", "default", "scale x2.0"]))
    for cid in ("kestrel-av", "aurora-defi"):
        print(f"\n### {cid}\n")
        print(cases_table(cases, cid))
