"""Write docs/process/HISTORY.md: a dated trail of every commit (author name, subject), from git, never edited by hand.

    python scripts/history_log.py

Lists this repository's non-merge commits on all local branches, and, when the remote ref course/main is present (git fetch course), the
official course repository's commits too. Author names are git author names, no e-mail addresses. Merge commits are listed separately.
"""

from __future__ import annotations

import subprocess
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "process" / "HISTORY.md"


def git(*a: str) -> str:
    return subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True, check=True).stdout


def rows(*revs: str, merges: bool = False) -> list[tuple[str, str, str, str]]:
    flag = "--merges" if merges else "--no-merges"
    out = git("log", *revs, flag, "--format=%ad\t%h\t%an\t%s", "--date=short")
    return sorted((tuple(ln.split("\t", 3)) for ln in out.splitlines() if ln.count("\t") >= 3), key=lambda r: (r[0], r[1]))  # type: ignore[misc]


def table(rs: list[tuple[str, str, str, str]]) -> str:
    esc = lambda s: s.replace("|", "\\|")  # noqa: E731
    return "| Date | Commit | Author name | Subject |\n|---|---|---|---|\n" + "\n".join(f"| {d} | `{h}` | {esc(a)} | {esc(s)} |" for d, h, a, s in rs) + "\n"


def main() -> int:
    have_course = subprocess.run(["git", "rev-parse", "--verify", "-q", "course/main"], cwd=ROOT, capture_output=True).returncode == 0
    mine = rows("--branches")
    text = ["# History: a dated trail of the work\n",
            "Generated by `scripts/history_log.py` from git; never edited by hand. Author names are the git author names as recorded (no e-mail addresses),\n"
            "and they are not matched to team members by any file in the repository. Two sources of history exist; `report/` section 5.4 says how they differ.\n"]
    c = Counter(a for _, _, a, _ in mine)
    text.append(f"\n## This repository: all local branches ({len(mine)} non-merge commits)\n\nBy author name: " + ", ".join(f"{a} {n}" for a, n in c.most_common()) + ".\n\n" + table(mine))
    merges = rows("--branches", merges=True)
    text.append(f"\n## Merge commits in this repository ({len(merges)})\n\n" + table(merges))
    if have_course:
        cr = rows("course/main")
        cc = Counter(a for _, _, a, _ in cr)
        text.append(f"\n## The official course repository, `course/main` ({len(cr)} non-merge commits)\n\nBy author name: " + ", ".join(f"{a} {n}" for a, n in cc.most_common()) + ".\n\n" + table(cr))
    OUT.write_text("".join(text), encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT), f"({len(mine)} + {len(merges)} merges" + (f" + {len(cr)} official)" if have_course else ")"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
